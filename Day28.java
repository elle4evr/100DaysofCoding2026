public class Day28 {
    /**
     * @author Efraim
     */
    public static void main(String[] args) {
        // oprator perbandingan == dan !=
        int a = 5;
        int b = 10;
        int c = 5;
       boolean h1 = a == b; // false karna value a dan b beda
       System.out.println(h1);
       boolean h2 = a == c; // true karna value a dan c sama
       System.out.println(h2);
       boolean h3 = a != b; //  true karna value a dan b tidak sama
       System.out.println(h3);
    }
}
